"""Save coder-extracted arrays using field metadata from the confirmed card."""
import json
from pathlib import Path

import numpy as np


def save_fields(fields, unknowns, output):
    if not isinstance(fields, list) or len(fields) != len(unknowns):
        raise ValueError('postprocess_fields must be a list with one coordinate/value pair per card field.')
    arrays = {}
    for i, (pair, field) in enumerate(zip(fields, unknowns)):
        if not isinstance(pair, (tuple, list)) or len(pair) != 2:
            raise ValueError(f'Field {i} must provide (coordinates, values).')
        points, values = map(np.asarray, pair)
        shape = field['shape']
        components = int(np.prod(shape)) if shape else 1
        if points.ndim != 2 or points.shape[1] != 3 or not len(points):
            raise ValueError(f'Field {i}: coordinates must have one row per location and three columns.')
        allowed = {(len(points), components), (len(points), *shape)}
        if values.shape not in allowed:
            raise ValueError(f'Field {i}: each coordinate row needs {components} value components; got {values.shape}.')
        if points.dtype.kind != 'f' or values.dtype.kind not in 'fc':
            raise ValueError('Coordinates and values must be floating-point arrays.')
        if not np.isfinite(points).all():
            raise ValueError('Coordinates must be finite.')
        arrays[f'f{i}_points'] = points.copy()
        arrays[f'f{i}_values'] = values.reshape(len(points), components).copy()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    np.savez(output / 'solution.npz', **arrays)
    manifest = {'fields': [{'name': f['name'], 'shape': f['shape'], 'index': i}
                           for i, f in enumerate(unknowns)]}
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


def attach(session, unknowns):
    """Append server storage in the retained interpreter, preserving coder line numbers."""
    execute = session.execute

    def execute_and_save(source, output, response, timeout=120):
        source = Path(source)
        combined = source.with_name('executed_with_server_export.py')
        suffix = ('\n\n# Server-owned storage; not generated by the coder.\n'
                  'from experiments.tensile_server_export_20261117.server_export import save_fields as _server_save_fields\n'
                  f'_server_save_fields(globals().get("postprocess_fields"), {unknowns!r}, POSTPROCESS_OUTPUT_DIR)\n')
        combined.write_text(source.read_text() + suffix)
        return execute(combined, output, response, timeout=timeout)

    session.execute = execute_and_save
